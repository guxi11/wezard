import assert from "node:assert/strict";
import { mkdtempSync, writeFileSync, readFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import pino from "pino";
import { createWorkflowNodes, resultDigest } from "../daemon/workflow-nodes.js";
import { createReceipts } from "../daemon/receipts.js";

const dir = mkdtempSync(join(tmpdir(), "wezard-workflow-"));
const file = join(dir, "nodes.json");
let w = createWorkflowNodes(file);
const a = w.begin("owner", "job", "build", "tA", "worker", false);
w.intent(a.id, { from: "owner", to: "worker", channel: "", job: "job", turn: "tA" });
// Simulate process death after durable intent, before/after injection confirmation.
w = createWorkflowNodes(file);
assert.equal(w.byTurn("owner", "tA")?.execution, "dispatch-unknown");
assert.throws(() => w.begin("owner", "job", "build", "tRetry", "worker", false));
w.outcome("owner", "tA", "done", "late RESULT");
assert.equal(w.byTurn("owner", "tA")?.execution, "dispatch-unknown");
assert.throws(() => w.verdict("other", a.id, "sent", undefined, "transcript"));
w.verdict("owner", a.id, "sent", undefined, "transcript contains tA");
w.outcome("owner", "tA", "need", "NEED: input");
assert.equal(w.byTurn("owner", "tA")?.execution, "needs-input");
w = createWorkflowNodes(file);
assert.equal(w.byTurn("owner", "tA")?.execution, "needs-input", "NEED survives actual store reconstruction");
assert.equal(w.begin("owner", "job", "build", "tA", "worker", false).id, a.id);
w.intent(a.id, { from: "owner", to: "worker", channel: "", turn: "tA" });
w.dispatched(a.id, false);
assert.equal(w.byTurn("owner", "tA")?.execution, "dispatch-unknown");
w.verdict("owner", a.id, "sent", undefined, "continuation turn observed in transcript");
w.outcome("owner", "tA", "done", "RESULT: tests failed");
const released: string[] = [];
const delivered: string[] = [];
const pause = (ms: number) => new Promise((resolve) => setTimeout(resolve, ms));
const r = createReceipts({
  release: async (h) => { released.push(h.turn); return { ok: true }; },
  workflowPrereq: w.prereq, log: pino({ level: "silent" }),
  idleNow: async () => true, untilIdle: async () => ({ idle: true }), paneLive: async () => true,
  replyFor: () => undefined, deliver: async (_to, _body, meta) => { delivered.push(meta.turn); return { ok: true }; }, nameOf: (x) => x,
});
assert.equal(r.prereqs("owner", ["tA"])[0]?.state, "pending", "done/RESULT is not acceptance");
assert.equal(r.prereqs("owner", ["tA"], { tA: { to: "worker", status: "done", body: "legacy snapshot" } })[0]?.state, "pending", "tracked state overrides cached done snapshot");
r.hold({ from: "owner", to: "child", turn: "tBlocked", at: Date.now(), after: ["tA"], body: {}, channel: "", job: "job" });
await pause(3200);
assert.equal(released.length, 0, "done failure must not release held successor");
assert.throws(() => w.verdict("owner", a.id, "accepted", "wrong", "reviewed"));
w.verdict("owner", a.id, "rejected", resultDigest("RESULT: tests failed"), "tests failed");
assert.equal(r.prereqs("owner", ["tA"])[0]?.state, "failed");
await pause(3200);
assert.equal(released.length, 0);
assert.ok(delivered.includes("tBlocked"), "rejected successor is canceled");
assert.throws(() => w.begin("owner", "job", "build", "tRetry", "worker", false), "rejection alone doesn't prove execution stopped");
w.verdict("owner", a.id, "stopped", undefined, "pane idle, no running subprocess");
const retry = w.begin("owner", "job", "build", "tRetry", "worker", false);
assert.notEqual(a.id, retry.id);
w.intent(retry.id, { from: "owner", to: "worker", job: "job", channel: "", turn: "tRetry" });
w.dispatched(retry.id, true);
w.outcome("owner", "tA", "done", "RESULT: late success");
assert.equal(w.byTurn("owner", "tA")?.body, "RESULT: tests failed");
w.outcome("owner", "tRetry", "done", "RESULT: fixed");
const artifact = join(dir, "artifact");
writeFileSync(artifact, "v1");
assert.throws(() => w.verdict("owner", retry.id, "accepted", resultDigest("RESULT: fixed"), "reviewed", [{ path: join(dir, "missing"), sha256: resultDigest("v1") }]));
r.hold({ from: "owner", to: "child", turn: "tAllowed", at: Date.now(), after: ["tRetry"], body: {}, channel: "", job: "job" });
w.verdict("owner", retry.id, "accepted", resultDigest("RESULT: fixed"), "tests and review passed", [{ path: artifact, sha256: resultDigest("v1") }]);
assert.equal(r.prereqs("owner", ["tRetry"])[0]?.state, "done");
await pause(3200);
assert.deepEqual(released, ["tAllowed"], "only accepted result releases successor");
writeFileSync(artifact, "v2");
assert.equal(r.prereqs("owner", ["tRetry"])[0]?.state, "failed");
const second = w.begin("owner", "job", "review", "tSecond", "worker", false);
assert.notEqual(second.id, retry.id);
assert.equal(w.list("owner", "job").length, 3, "same wizard node histories survive");
const restored = createWorkflowNodes(file);
assert.equal(restored.list("owner").length, 3);
assert.equal(restored.byTurn("owner", "tA")?.acceptance, "rejected");
assert.equal(restored.prereq("owner", "tSecond")?.state, "pending");
const claimed = w.begin("owner", "job", "claimed", "tClaim", "another", false);
w.intent(claimed.id, { from: "owner", to: "another", channel: "", job: "job", turn: "tClaim" });
w.dispatched(claimed.id, true);
w.outcome("owner", "tClaim", "done", "");
assert.equal(w.byTurn("owner", "tClaim")?.execution, "dispatch-unknown");
assert.throws(() => w.verdict("owner", claimed.id, "accepted", resultDigest(""), "no body"));
const canceled = w.begin("owner", "job", "canceled", "tCancel", "cancel-worker", false);
w.intent(canceled.id, { from: "owner", to: "cancel-worker", channel: "", turn: "tCancel" });
w.outcome("owner", "tCancel", "canceled", "cancel while injecting");
w.dispatched(canceled.id, true);
w.outcome("owner", "tCancel", "done", "late result");
assert.equal(w.byTurn("owner", "tCancel")?.status, "canceled");
r.register({ from: "owner", to: "legacy", channel: "", turn: "legacy" }, false);
assert.equal(r.prereqs("owner", ["legacy"])[0]?.state, "done", "legacy claim semantics retained");
assert.equal(r.prereqs("other", ["tA"])[0]?.state, "unknown");
writeFileSync(join(dir, "bad.json"), "not json");
assert.throws(() => createWorkflowNodes(join(dir, "bad.json")), "corruption fails closed");
const before = readFileSync(file, "utf8");
const broken = createWorkflowNodes(join(dir, "child", "nodes.json"));
writeFileSync(join(dir, "child"), "cannot be directory");
assert.throws(() => broken.begin("o", "j", "n", "t", "w", false), "persist failure blocks intent");
assert.equal(readFileSync(file, "utf8"), before);
const legacyPath = join(dir, "legacy-nodes.json");
const legacyBody = `RESULT: old build\nARTIFACT: ${artifact} — old output`;
writeFileSync(legacyPath, JSON.stringify([{ ...a, execution: "terminal", acceptance: "accepted", status: "done", body: legacyBody, digest: resultDigest(legacyBody), files: [{ path: artifact, sha256: resultDigest("v2") }] }]));
const migrated = createWorkflowNodes(legacyPath);
assert.equal(migrated.byTurn("owner", "tA")?.acceptance, "pending", "first-slice accepted files need new validation, not boot failure");
assert.equal(migrated.prereq("owner", "tA")?.state, "pending");
const scoped = createWorkflowNodes(join(dir, "scoped-cancel.json"));
scoped.begin("owner", "job", "current", "current", "target", true);
scoped.begin("owner", "job", "queued", "queued", "target", true);
scoped.begin("other", "job", "other", "other", "target", true);
assert.equal(scoped.cancel("target", undefined, undefined, undefined, (x) => x.from === "owner" && x.turn === "current"), 1);
assert.equal(scoped.byTurn("owner", "queued")?.canceled, undefined);
assert.equal(scoped.byTurn("other", "other")?.canceled, undefined);
assert.equal(scoped.cancel("target", undefined, undefined, undefined, () => false), 0, "non-peer round cancels no attempt");
assert.equal(scoped.cancel("target"), 2, "end retains target-wide scope");
console.log("workflow nodes: identity, acceptance, NEED/re, unknown recovery, retries, late events, versions, legacy and fail-closed passed");
