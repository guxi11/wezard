import assert from "node:assert/strict";
import { mkdtempSync, mkdirSync, renameSync, writeFileSync, readFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { loadJobStore } from "../daemon/jobs.js";
import { createLedger } from "../daemon/pending-items.js";
import { loadJsonMap } from "../shared/json-map-store.js";
import type { Item } from "../daemon/pending-items.js";

const dir = mkdtempSync(join(tmpdir(), "wezard-accounting-"));
const file = join(dir, "jobs.json");
let jobs = loadJobStore(file);
const j = jobs.open("chat", "owner", "one dispatch", { maxTurns: 1 });
const member = { target: "worker", task: "original task", spawned: false, role: "expert" as const };
jobs.account(j.id, "leg1", member, "task");
jobs.settle(j.id, "worker", "done", [], { dispatchKey: "leg1" });
jobs = loadJobStore(file);
jobs.account(j.id, "leg1", member, "task", false, true);
assert.equal(jobs.get(j.id)?.turns, 1);
assert.equal(jobs.get(j.id)?.members[0].outcome, "done", "recovery must retain a later terminal member");
assert.throws(() => jobs.account(j.id, "leg2", member, "task"), /budget/);
// Original NEED/re budget policy exempts its check, but still counts the actual leg.
jobs.account(j.id, "leg2", { ...member, task: "" }, "task", true);
assert.equal(jobs.get(j.id)?.turns, 2);
assert.equal(jobs.get(j.id)?.members[0].task, "original task");
assert.equal(jobs.get(j.id)?.members[0].outcome, undefined);
const root = jobs.open("chat", "owner", "plan gate", { kind: "req", maxTurns: 1 });
const lead = { ...member, role: "lead" as const };
jobs.account(root.id, "lead1", lead, "task");
assert.equal(jobs.get(root.id)?.gate?.g2, undefined);
jobs.account(root.id, "lead2", { ...lead, task: "" }, "task", true, false, true);
assert.ok(jobs.get(root.id)?.gate?.g2, "actual NEED continuation keeps the original G2 semantics");
const before = readFileSync(file, "utf8");
const other = jobs.open("chat", "owner", "failed write");
renameSync(file, file + ".backup");
mkdirSync(file);
assert.throws(() => jobs.account(other.id, "failed", member, "task"));
assert.equal(jobs.get(other.id)?.turns, undefined, "failed strict mutation must not advance memory");
assert.equal(jobs.get(other.id)?.members.length, 0);
assert.throws(() => jobs.account(other.id, "retry", member, "task"), /previously failed/);
assert.ok(before.includes("leg1"));
const corrupt = join(dir, "bad.json");
writeFileSync(corrupt, "not JSON");
assert.throws(() => loadJobStore(corrupt));
assert.deepEqual(loadJsonMap(corrupt).all(), {}, "advisory callers retain tolerant behavior");
const store = loadJsonMap<Item>(join(dir, "ledger.json"), undefined, { strict: true });
let ledger = createLedger(store);
const item = { turn: "turn", owner: "owner", to: "worker", text: "original", at: 1 };
ledger.dispatch("leg1", item);
ledger.outcome("owner", "turn", "done", "RESULT: finished", true);
ledger = createLedger(loadJsonMap<Item>(join(dir, "ledger.json"), undefined, { strict: true }));
ledger.dispatch("leg1", item);
assert.equal(ledger.openOf("owner").length, 0, "duplicate recovery must not reopen a closed ledger item");
ledger.dispatch("leg2", { ...item, text: "clarify", at: 2 });
assert.equal(ledger.openOf("owner").length, 1, "a new continuation leg reopens once");
assert.equal(ledger.openOf("owner")[0].dispatches?.length, 2);
console.log("workflow accounting: durable idempotent budget/member/ledger, NEED policy and strict failure passed");
